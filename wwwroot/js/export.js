window.gpuExport = (() => {
    const palette = {
        navy: [15, 23, 42],
        blue: [37, 99, 235],
        cyan: [14, 165, 233],
        slate: [71, 85, 105],
        muted: [100, 116, 139],
        line: [203, 213, 225],
        pale: [241, 245, 249],
        paleBlue: [239, 246, 255],
        white: [255, 255, 255],
    };

    const ensureDeps = () => {
        if (typeof window.jspdf?.jsPDF !== "function")
            throw new Error("The jsPDF library did not load. Check access to cdn.jsdelivr.net and try again.");
        const probe = new window.jspdf.jsPDF();
        if (typeof probe.autoTable !== "function")
            throw new Error("The PDF table library did not load. Check access to cdn.jsdelivr.net and try again.");
    };

    const read = (source, name) => {
        if (!source) return undefined;
        const camel = name.charAt(0).toLowerCase() + name.slice(1);
        return source[camel] ?? source[name];
    };

    const value = input => input === null || input === undefined || input === "" ? "-" : `${input}`;
    const number = input => Number.isFinite(Number(input)) ? Number(input).toLocaleString() : value(input);

    const drawHeader = (pdf, section) => {
        const width = pdf.internal.pageSize.getWidth();
        pdf.setFillColor(...palette.navy);
        pdf.rect(0, 0, width, 24, "F");
        pdf.setFillColor(...palette.blue);
        pdf.rect(0, 24, width, 1.5, "F");
        pdf.setTextColor(...palette.white);
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(15);
        pdf.text("GPU MONITOR", 14, 10);
        pdf.setFont("helvetica", "normal");
        pdf.setFontSize(8);
        pdf.text("ENGINEERING LOG REPORT", 14, 16);
        pdf.setFontSize(10);
        pdf.text(section, width - 14, 14, { align: "right" });
        pdf.setTextColor(...palette.navy);
    };

    const drawFooter = pdf => {
        const pages = pdf.getNumberOfPages();
        for (let page = 1; page <= pages; page++) {
            pdf.setPage(page);
            const width = pdf.internal.pageSize.getWidth();
            const height = pdf.internal.pageSize.getHeight();
            pdf.setDrawColor(...palette.line);
            pdf.line(14, height - 12, width - 14, height - 12);
            pdf.setFont("helvetica", "normal");
            pdf.setFontSize(7.5);
            pdf.setTextColor(...palette.muted);
            pdf.text("Generated by GPU Monitor Log Parser", 14, height - 7);
            pdf.text(`Page ${page} of ${pages}`, width - 14, height - 7, { align: "right" });
        }
    };

    const sectionTitle = (pdf, title, subtitle, y) => {
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(12);
        pdf.setTextColor(...palette.navy);
        pdf.text(title, 14, y);
        if (subtitle) {
            pdf.setFont("helvetica", "normal");
            pdf.setFontSize(7.5);
            pdf.setTextColor(...palette.muted);
            pdf.text(subtitle, 14, y + 4.5);
            return y + 8;
        }
        return y + 4;
    };

    const addTable = (pdf, rows, startY, columns, options = {}) => {
        if (!rows?.length) return startY;
        pdf.autoTable({
            columns: columns.map(column => ({ header: column.header, dataKey: column.key })),
            body: rows,
            startY,
            theme: "grid",
            margin: { left: 14, right: 14, bottom: 18 },
            styles: {
                font: "helvetica",
                fontSize: 8,
                cellPadding: 2.2,
                textColor: palette.navy,
                lineColor: palette.line,
                lineWidth: 0.15,
                valign: "middle",
            },
            headStyles: {
                fillColor: palette.navy,
                textColor: palette.white,
                fontStyle: "bold",
            },
            alternateRowStyles: { fillColor: palette.pale },
            ...options,
        });
        return pdf.lastAutoTable.finalY + 7;
    };

    const drawOverviewCards = (pdf, report, y) => {
        const cards = [
            ["UTILIZATION FILTER", value(read(report, "Filter"))],
            ["MATCHING SAMPLES", `${number(read(report, "MatchingRows"))} / ${number(read(report, "TotalRows"))}`],
            ["COVERAGE", value(read(report, "Coverage"))],
            ["DURATION", value(read(report, "Duration"))],
        ];
        const gap = 3;
        const width = (182 - gap * 3) / 4;
        cards.forEach((card, index) => {
            const x = 14 + index * (width + gap);
            pdf.setFillColor(...palette.paleBlue);
            pdf.setDrawColor(191, 219, 254);
            pdf.roundedRect(x, y, width, 18, 2, 2, "FD");
            pdf.setFont("helvetica", "bold");
            pdf.setFontSize(6.5);
            pdf.setTextColor(...palette.blue);
            pdf.text(card[0], x + 3, y + 5.5);
            pdf.setFontSize(10);
            pdf.setTextColor(...palette.navy);
            pdf.text(card[1], x + 3, y + 12.5, { maxWidth: width - 6 });
        });
        return y + 23;
    };

    const canvasImage = (id, width, height) => {
        const reportImage = window.gpuCharts?.exportImage?.(id, width, height);
        if (reportImage) return reportImage;
        const source = document.getElementById(id);
        if (!(source instanceof HTMLCanvasElement) || !source.width || !source.height) return null;
        const output = document.createElement("canvas");
        output.width = source.width;
        output.height = source.height;
        const context = output.getContext("2d");
        context.fillStyle = "#ffffff";
        context.fillRect(0, 0, output.width, output.height);
        context.drawImage(source, 0, 0);
        return {
            data: output.toDataURL("image/png"),
            width: output.width,
            height: output.height,
        };
    };

    const addChart = (pdf, chart, y, maxHeight = 66) => {
        const image = canvasImage(chart.id, 1800, 620);
        if (!image) return y;
        const pageWidth = pdf.internal.pageSize.getWidth();
        const availableWidth = pageWidth - 28;
        const renderedHeight = Math.min(maxHeight, availableWidth * image.height / image.width);
        const renderedWidth = renderedHeight * image.width / image.height;
        const x = 14 + (availableWidth - renderedWidth) / 2;
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(10);
        pdf.setTextColor(...palette.navy);
        pdf.text(chart.label, 14, y);
        pdf.setDrawColor(...palette.line);
        pdf.setFillColor(...palette.white);
        pdf.roundedRect(14, y + 3, availableWidth, renderedHeight + 4, 1.5, 1.5, "FD");
        pdf.addImage(image.data, "PNG", x, y + 5, renderedWidth, renderedHeight, undefined, "FAST");
        return y + renderedHeight + 13;
    };

    const addTimelinePage = (pdf, id, title, subtitle) => {
        const image = canvasImage(id, 2200, 680);
        if (!image) return false;
        pdf.addPage("a4", "landscape");
        drawHeader(pdf, title);
        let y = sectionTitle(pdf, title, subtitle, 36);
        const pageWidth = pdf.internal.pageSize.getWidth();
        const pageHeight = pdf.internal.pageSize.getHeight();
        const maxWidth = pageWidth - 28;
        const maxHeight = pageHeight - y - 25;
        const scale = Math.min(maxWidth / image.width, maxHeight / image.height);
        const width = image.width * scale;
        const height = image.height * scale;
        const x = (pageWidth - width) / 2;
        pdf.setDrawColor(...palette.line);
        pdf.roundedRect(x - 2, y, width + 4, height + 4, 1.5, 1.5, "S");
        pdf.addImage(image.data, "PNG", x, y + 2, width, height, undefined, "FAST");
        return true;
    };

    const normalizeStateRows = rows => (rows || []).map(row => ({
        state: value(read(row, "State")),
        samples: number(read(row, "Samples")),
        periods: number(read(row, "Periods")),
    }));

    const normalizeCappingRows = rows => (rows || []).map(row => ({
        reason: value(read(row, "Reason")),
        samples: number(read(row, "Samples")),
        periods: number(read(row, "Periods")),
    }));

    const exportEngineeringPdf = async (report, pStates, capping, filename) => {
        ensureDeps();
        window.gpuCharts?.timelineCommand?.("chart-pstate-timeline", "full");
        window.gpuCharts?.timelineCommand?.("chart-capping-timeline", "full");
        const { jsPDF } = window.jspdf;
        const pdf = new jsPDF("p", "mm", "a4");
        drawHeader(pdf, "Test summary");

        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(20);
        pdf.setTextColor(...palette.navy);
        pdf.text("GPU Performance Report", 14, 38);
        pdf.setFont("helvetica", "normal");
        pdf.setFontSize(8);
        pdf.setTextColor(...palette.muted);
        pdf.text(`Generated ${new Date().toLocaleString()}`, 14, 44);

        let y = drawOverviewCards(pdf, report, 50);
        y = sectionTitle(pdf, "Test identity", "Source and GPU configuration used for this report.", y);
        const identity = [
            { field: "Source file", value: value(read(report, "SourceFile")) },
            { field: "Test date", value: value(read(report, "Date")) },
            { field: "GPU", value: value(read(report, "BrandName")) },
            { field: "VBIOS", value: value(read(report, "VbiosVersion")) },
            { field: "Driver", value: value(read(report, "DriverVersion")) },
            { field: "Utilization column", value: value(read(report, "UtilColumn")) },
            { field: "Power column", value: value(read(report, "PowerColumn")) },
        ];
        y = addTable(pdf, identity, y, [
            { header: "Field", key: "field" },
            { header: "Value", key: "value" },
        ], { columnStyles: { field: { cellWidth: 42, fontStyle: "bold" } } });

        y = sectionTitle(pdf, "Filtered performance metrics", `Calculated from samples in the inclusive ${value(read(report, "Filter"))} utilization range.`, y);
        const metrics = [
            ["GPU temperature", "C", "GpuTjMin", "GpuTjAvg", "GpuTjMax"],
            ["Memory temperature", "C", "MemTjMin", "MemTjAvg", "MemTjMax"],
            ["Power", "W", "PowerMin", "PowerAvg", "PowerMax"],
            ["GPC clock", "MHz", "GpcClockMin", "GpcClockAvg", "GpcClockMax"],
            ["Memory clock", "MHz", "MemoryClockMin", "MemoryClockAvg", "MemoryClockMax"],
        ].map(metric => ({
            metric: metric[0],
            unit: metric[1],
            minimum: value(read(report, metric[2])),
            average: value(read(report, metric[3])),
            maximum: value(read(report, metric[4])),
        }));
        y = addTable(pdf, metrics, y, [
            { header: "Metric", key: "metric" },
            { header: "Unit", key: "unit" },
            { header: "Minimum", key: "minimum" },
            { header: "Average", key: "average" },
            { header: "Maximum", key: "maximum" },
        ], { columnStyles: { metric: { cellWidth: 50 }, unit: { cellWidth: 20 } } });

        const stateRows = normalizeStateRows(pStates);
        const cappingRows = normalizeCappingRows(capping);
        if (stateRows.length || cappingRows.length) {
            pdf.addPage("a4", "portrait");
            drawHeader(pdf, "Full-test activity");
            y = sectionTitle(pdf, "Full-test activity", "State and capping counts use every sample in the complete test, independent of the utilization filter.", 36);
            if (stateRows.length) {
                pdf.setFont("helvetica", "bold");
                pdf.setFontSize(9);
                pdf.text(`P-State activity · ${number(read(report, "PStateSamples"))} samples · ${number(read(report, "PStatePeriods"))} periods`, 14, y);
                y = addTable(pdf, stateRows, y + 3, [
                    { header: "P-State", key: "state" },
                    { header: "Samples", key: "samples" },
                    { header: "Continuous periods", key: "periods" },
                ]);
            }
            if (cappingRows.length) {
                pdf.setFont("helvetica", "bold");
                pdf.setFontSize(9);
                pdf.text(`Capping activity · ${number(read(report, "CappingSamples"))} active samples · ${number(read(report, "CappingPeriods"))} periods`, 14, y);
                addTable(pdf, cappingRows, y + 3, [
                    { header: "Reason", key: "reason" },
                    { header: "Samples", key: "samples" },
                    { header: "Continuous periods", key: "periods" },
                ]);
            }
        }

        const performanceCharts = [
            { id: "chart-gpu", label: "GPU temperature" },
            { id: "chart-memory", label: "Memory temperature" },
            { id: "chart-power", label: "Power" },
            { id: "chart-gpc-clock", label: "GPC clock" },
            { id: "chart-memory-clock", label: "Memory clock" },
            { id: "chart-scatter", label: "Power versus GPU temperature" },
        ].filter(chart => document.getElementById(chart.id));
        if (performanceCharts.length) {
            pdf.addPage("a4", "portrait");
            drawHeader(pdf, "Performance charts");
            let chartY = sectionTitle(pdf, "Filtered performance charts", `Samples shown use the inclusive ${value(read(report, "Filter"))} utilization range.`, 36);
            for (const chart of performanceCharts) {
                if (chartY > pdf.internal.pageSize.getHeight() - 82) {
                    pdf.addPage("a4", "portrait");
                    drawHeader(pdf, "Performance charts");
                    chartY = sectionTitle(pdf, "Filtered performance charts (continued)", null, 36);
                }
                chartY = addChart(pdf, chart, chartY, 65);
            }
        }

        addTimelinePage(pdf, "chart-pstate-timeline", "P-State timeline", "Continuous state periods across the complete test.");
        addTimelinePage(pdf, "chart-capping-timeline", "Capping timeline", "Active capping reasons and overlaps across the complete test.");

        drawFooter(pdf);
        pdf.save(filename || "gpu-log-report.pdf");
        return true;
    };

    return { exportEngineeringPdf };
})();
